#!/usr/bin/env node
/**
 * Офлайн-инструмент миграций для сред без доступа к binaries.prisma.sh.
 *
 * В обычной среде используйте штатные команды:
 *   npx prisma migrate dev / npx prisma migrate deploy
 *
 * Этот скрипт делает то же самое через официальный WASM-движок схем Prisma
 * (@prisma/schema-engine-wasm той же сборки, что и Prisma 7.10.1) и формирует
 * миграции в стандартном формате prisma/migrations — они совместимы с
 * `prisma migrate deploy`.
 *
 *   node scripts/prisma-offline.mjs create <name>   — создать миграцию из изменений схемы
 *   node scripts/prisma-offline.mjs deploy          — применить неприменённые миграции
 */
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { createHash, randomUUID } from "node:crypto";
import path from "node:path";
import "dotenv/config";
import pg from "pg";
import { SchemaEngine } from "@prisma/schema-engine-wasm";
import { PrismaPg } from "@prisma/adapter-pg";
import { bindMigrationAwareSqlAdapterFactory } from "@prisma/driver-adapter-utils";

const ROOT = path.resolve(import.meta.dirname, "..");
const SCHEMA = path.join(ROOT, "prisma/schema.prisma");
const MIG_DIR = path.join(ROOT, "prisma/migrations");
const SNAPSHOT = path.join(MIG_DIR, "schema.snapshot.prisma");

async function diffSql(fromSchema, toSchema) {
  const adapter = bindMigrationAwareSqlAdapterFactory(
    new PrismaPg({ connectionString: process.env.DATABASE_URL }),
  );
  const engine = await SchemaEngine.new({ datamodels: undefined }, () => {}, adapter);
  const from = fromSchema
    ? { tag: "schemaDatamodel", files: [{ path: "from.prisma", content: fromSchema }] }
    : { tag: "empty" };
  const res = await engine.diff({
    from,
    to: { tag: "schemaDatamodel", files: [{ path: "schema.prisma", content: toSchema }] },
    script: true,
    exitCode: null,
    filters: { externalTables: [], externalEnums: [] },
  });
  return res.stdout ?? "";
}

async function create(name) {
  if (!name) throw new Error("Укажите имя миграции");
  const current = await readFile(SCHEMA, "utf8");
  const previous = existsSync(SNAPSHOT) ? await readFile(SNAPSHOT, "utf8") : null;
  const sql = await diffSql(previous, current);
  if (!sql.trim() || /^-- This is an empty migration/.test(sql.trim())) {
    console.log("Изменений схемы нет — миграция не создана.");
    return;
  }
  const ts = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const dir = path.join(MIG_DIR, `${ts}_${name}`);
  await mkdir(dir, { recursive: true });
  await writeFile(path.join(dir, "migration.sql"), sql);
  await writeFile(SNAPSHOT, current);
  if (!existsSync(path.join(MIG_DIR, "migration_lock.toml"))) {
    await writeFile(
      path.join(MIG_DIR, "migration_lock.toml"),
      '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
    );
  }
  console.log(`Создана миграция ${path.relative(ROOT, dir)}`);
}

async function deploy() {
  const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
  await client.connect();
  try {
    await client.query(`CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
      "id" VARCHAR(36) PRIMARY KEY NOT NULL,
      "checksum" VARCHAR(64) NOT NULL,
      "finished_at" TIMESTAMPTZ,
      "migration_name" VARCHAR(255) NOT NULL,
      "logs" TEXT,
      "rolled_back_at" TIMESTAMPTZ,
      "started_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
      "applied_steps_count" INTEGER NOT NULL DEFAULT 0)`);
    const applied = new Set(
      (await client.query(`SELECT migration_name FROM "_prisma_migrations" WHERE finished_at IS NOT NULL`)).rows.map(
        (r) => r.migration_name,
      ),
    );
    const dirs = (await readdir(MIG_DIR, { withFileTypes: true }))
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();
    let count = 0;
    for (const name of dirs) {
      if (applied.has(name)) continue;
      const sql = await readFile(path.join(MIG_DIR, name, "migration.sql"), "utf8");
      const checksum = createHash("sha256").update(sql).digest("hex");
      const id = randomUUID();
      await client.query("BEGIN");
      try {
        await client.query(sql);
        await client.query(
          `INSERT INTO "_prisma_migrations" (id, checksum, finished_at, migration_name, applied_steps_count) VALUES ($1,$2,now(),$3,1)`,
          [id, checksum, name],
        );
        await client.query("COMMIT");
        count++;
        console.log(`Применена ${name}`);
      } catch (e) {
        await client.query("ROLLBACK");
        throw e;
      }
    }
    console.log(count ? `Готово: ${count} миграций.` : "Все миграции уже применены.");
  } finally {
    await client.end();
  }
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === "create") await create(arg);
else if (cmd === "deploy") await deploy();
else {
  console.log("Использование: node scripts/prisma-offline.mjs create <name> | deploy");
  process.exit(1);
}
